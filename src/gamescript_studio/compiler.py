"""Export a self-contained browser game into a new directory."""

import html
import json
import os
from pathlib import Path
from importlib.resources import files
import shutil
import tempfile
from .model import validate


def atomic_text(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".write-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def compile_script(project):
    project = validate(project)
    runtime = (
        files("gamescript_studio").joinpath("templates/runtime.js").read_text(encoding="utf-8")
    )
    # Serialized data is assigned in an external JS file, never inserted into executable source.
    return (
        "/* Generated by GameScript Studio. MIT. */\nconst GAME_CONFIG = "
        + json.dumps(project, ensure_ascii=True)
        + ";\n"
        + runtime
    )


def export_game(project, destination):
    project = validate(project)
    dest = Path(destination).resolve()
    if dest.exists():
        raise FileExistsError("Choose a new output folder; existing folders are never overwritten.")
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".gss-", dir=dest.parent))
    try:
        (staging / "game.js").write_text(compile_script(project), encoding="utf-8")
        (staging / "project.json").write_text(json.dumps(project, indent=2), encoding="utf-8")
        page = (
            files("gamescript_studio").joinpath("templates/index.html").read_text(encoding="utf-8")
        )
        (staging / "index.html").write_text(
            page.replace("__TITLE__", html.escape(project["title"])), encoding="utf-8"
        )
        (staging / "LICENSE").write_text(
            files("gamescript_studio").joinpath("templates/LICENSE.txt").read_text(),
            encoding="utf-8",
        )
        os.rename(staging, dest)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return dest / "index.html"
